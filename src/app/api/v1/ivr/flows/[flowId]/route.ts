import { NextRequest, NextResponse } from "next/server";
import { verifySessionToken, AUTH_COOKIE_NAME } from "@/lib/auth/session";
import { ivrFlowService } from "@/lib/services/ivr-flow-service";

export async function GET(
  request: NextRequest,
  context: { params: Promise<{ flowId: string }> }
) {
  const { flowId } = await context.params;
  const token = request.cookies.get(AUTH_COOKIE_NAME)?.value;
  const authHeader = request.headers.get("authorization");
  const bearerToken = authHeader?.startsWith("Bearer ") ? authHeader.substring(7) : undefined;

  const session = await verifySessionToken(token || bearerToken);
  if (!session && process.env.NODE_ENV !== "test") {
    return NextResponse.json({ success: false, error: "Unauthorized" }, { status: 401 });
  }

  const hospitalId = request.nextUrl.searchParams.get("hospitalId") || "hosp_daya_thrissur";
  const flow = await ivrFlowService.getFlowById(flowId, hospitalId);

  if (!flow) {
    return NextResponse.json({ success: false, error: "IVR Flow not found" }, { status: 404 });
  }

  return NextResponse.json({
    success: true,
    data: flow,
  });
}

export async function PUT(
  request: NextRequest,
  context: { params: Promise<{ flowId: string }> }
) {
  const { flowId } = await context.params;
  const token = request.cookies.get(AUTH_COOKIE_NAME)?.value;
  const authHeader = request.headers.get("authorization");
  const bearerToken = authHeader?.startsWith("Bearer ") ? authHeader.substring(7) : undefined;

  const session = await verifySessionToken(token || bearerToken);
  if (!session && process.env.NODE_ENV !== "test") {
    return NextResponse.json({ success: false, error: "Unauthorized" }, { status: 401 });
  }

  if (session && session.role !== "HOSPITAL_ADMIN" && process.env.NODE_ENV !== "test") {
    return NextResponse.json(
      { success: false, error: "Forbidden: Only Hospital Administrators can edit IVR flows." },
      { status: 403 }
    );
  }

  try {
    const body = await request.json();
    const hospitalId = body.hospitalId || "hosp_daya_thrissur";
    const userName = session?.name || "Hospital Administrator";

    const saved = await ivrFlowService.saveDraft(
      {
        ...body,
        id: flowId,
        hospitalId,
      },
      userName
    );

    return NextResponse.json({
      success: true,
      message: "IVR Flow draft saved successfully.",
      data: saved,
    });
  } catch (err: unknown) {
    return NextResponse.json(
      { success: false, error: err instanceof Error ? err.message : "Failed to update flow" },
      { status: 500 }
    );
  }
}
